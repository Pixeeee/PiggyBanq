import assert from 'node:assert/strict';
import { chromium } from 'playwright';

const base = process.env.RELEASE_WEB_URL ?? 'http://127.0.0.1:3010';
const browser = await chromium.launch({ headless: true, ...(process.env.RELEASE_BROWSER_EXECUTABLE ? { executablePath: process.env.RELEASE_BROWSER_EXECUTABLE } : {}) });
try {
  const context = await browser.newContext({ ignoreHTTPSErrors: true });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${base}/signup`);
  assert.equal(await page.getByRole('button', { name: /Privy|Web3Auth|Open demo/ }).count(), 0);
  await page.getByRole('button', { name: 'Create a local wallet', exact: true }).click();
  const username = `browser_${Date.now().toString(36)}`;
  const password = 'BrowserRelease!2026';
  await page.getByLabel('Username', { exact: true }).fill(username);
  await page.getByLabel('Create new password', { exact: true }).fill(password);
  await page.getByLabel('Confirm password', { exact: true }).fill(password);
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Create password', exact: true }).click();
  await page.getByRole('button', { name: /Tap to reveal/ }).click();
  const phrase = (await page.locator('.stellar-phrase li').allTextContents()).join(' ');
  await page.getByRole('checkbox').check();
  await page.getByLabel('Confirm recovery phrase').fill(phrase);
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await page.waitForURL(`${base}/dashboard`, { timeout: 30000 });
  const sessionCookie = (await context.cookies()).find(cookie => cookie.name === 'piggybanq_wallet_session');
  assert.ok(sessionCookie?.httpOnly);
  assert.equal(sessionCookie.sameSite, 'Lax');
  if (base.startsWith('https:')) assert.equal(sessionCookie.secure, true);
  await page.reload();
  await page.waitForURL(`${base}/dashboard`);
  await page.goto(`${base}/dashboard/allocations`);
  await page.getByLabel('Amount', { exact: true }).fill('125.50');
  await page.getByRole('button', { name: 'Create allocation', exact: true }).click();
  await page.getByText('Allocation saved.', { exact: true }).waitFor();
  await page.reload();
  await page.getByText('PHP 125.50', { exact: true }).first().waitFor();
  await page.goto(`${base}/dashboard/profile`);
  await page.getByText('Profile synced.', { exact: true }).waitFor();
  await page.getByLabel('Profile name', { exact: true }).fill('Browser Verified');
  await page.getByRole('button', { name: 'Save profile', exact: true }).click();
  await page.getByText('Profile saved.', { exact: true }).waitFor();
  await page.reload();
  await page.getByText('Profile synced.', { exact: true }).waitFor();
  assert.equal(await page.getByLabel('Profile name', { exact: true }).inputValue(), 'Browser Verified');
  await page.goto(`${base}/dashboard/goals`);
  await page.goto(`${base}/dashboard/pockets`);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.route('**/backend/api/auth/logout', route => route.abort());
  await page.getByRole('button', { name: 'Logout' }).click();
  await page.getByRole('alert').filter({ hasText: 'Sign out failed' }).waitFor({ timeout: 5000 });
  assert.ok(page.url().includes('/dashboard'));
  await page.unroute('**/backend/api/auth/logout');
  await page.getByRole('button', { name: 'Logout' }).click();
  await page.waitForURL(`${base}/login`);
  await page.goto(`${base}/dashboard`);
  await page.waitForURL(`${base}/login`);
  const recoveredContext = await browser.newContext({ ignoreHTTPSErrors: true });
  const recovered = await recoveredContext.newPage();
  recovered.on('pageerror', error => errors.push(error.message));
  await recovered.goto(`${base}/login`);
  await recovered.getByRole('button', { name: 'Restore with recovery phrase', exact: true }).click();
  await recovered.getByLabel('Original username', { exact: true }).fill(username);
  await recovered.getByLabel('Secret Recovery Phrase', { exact: true }).fill(phrase);
  await recovered.getByLabel('New password for this device', { exact: true }).fill('RecoveredRelease!2026');
  await recovered.getByLabel('Confirm new password', { exact: true }).fill('RecoveredRelease!2026');
  await recovered.getByRole('button', { name: 'Restore and log in', exact: true }).click();
  await recovered.waitForURL(`${base}/dashboard`, { timeout: 30000 });
  await recovered.goto(`${base}/dashboard/allocations`);
  await recovered.getByText('PHP 125.50', { exact: true }).first().waitFor();
  const records = await recovered.evaluate(() => JSON.parse(localStorage.getItem('piggybanq.walletAccounts')));
  assert.equal(records.length, 1);
  assert.equal('vault' in records[0], false);
  assert.equal('secretKey' in records[0], false);
  assert.deepEqual(errors, []);
  console.log('PASS production signup, cookie, protected reload, allocations/profile persistence, responsive layout, logout and new-browser recovery.');
} finally {
  await browser.close();
}
